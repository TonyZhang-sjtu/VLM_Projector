"""Transfer an audited, exact list of completed runs without touching other runs.

The inventory is generated by collect_completed_download.py on Marlowe.
Usage: python download_completed.py AUDIT_DIR prepare|transfer|verify
"""
import argparse
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]


def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def save(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')


def prepare(audit, inventory):
    records, counts = [], Counter()
    groups = {e['run']: e['group'] for e in inventory['completed']}
    for f in inventory['files']:
        rel = Path(f['path'])
        if rel.is_absolute() or '..' in rel.parts:
            raise ValueError(f'Invalid inventory path: {rel}')
        path = ROOT / rel
        if path.resolve() != path:
            raise ValueError(f'Local symlink in destination path: {path}')
        state = ('same_size' if path.stat().st_size == f['size'] else 'different_size') if path.is_file() else 'missing'
        records.append(dict(path=f['path'], prior_state=state, size=f['size'], group=groups[f['owners'][0]]))
        counts[state] += 1
        counts[state + '_bytes'] += f['size']
    free = shutil.disk_usage(ROOT).free
    required = counts['missing_bytes'] + counts['different_size_bytes']
    if free < required + 10 * 1024**3:
        raise RuntimeError(f'Insufficient disk space: {free} free; {required} additional bytes')
    (audit / 'files.from0').write_bytes(b''.join(f['path'].encode() + b'\0' for f in inventory['files']))
    save(audit / 'local_before.json', dict(counts=counts, free_bytes=free, files=records))
    print(json.dumps(dict(counts=counts, free_gib=free / 1024**3), indent=2), flush=True)


def transfer(audit, inventory):
    args = ['rsync', '-aH', '--checksum', '--no-owner', '--no-group', '--partial',
            '--partial-dir=.rsync-partial', '--from0', '--files-from=' + str(audit / 'files.from0'),
            '--backup', '--backup-dir=' + str(audit / 'replaced_files'),
            '--info=progress2,stats2', '--outbuf=L', '--log-file=' + str(audit / 'rsync_files.log'),
            '--log-file-format=%i %l %n%L', '-e',
            'ssh -o ServerAliveInterval=60 -o ServerAliveCountMax=3',
            'marlowe:' + inventory['remote_root'] + '/', str(ROOT) + '/']
    save(audit / 'transfer_command.json', args)
    started = datetime.now(timezone.utc).isoformat()
    code = subprocess.call(args)
    save(audit / 'transfer_status.json', dict(started_at=started, ended_at=datetime.now(timezone.utc).isoformat(), returncode=code))
    return code


def verify(audit, inventory):
    def one(f):
        p = ROOT / f['path']
        if not p.is_file():
            return dict(path=f['path'], error='missing')
        if p.stat().st_size != f['size']:
            return dict(path=f['path'], error='size mismatch')
        if f.get('sha256'):
            got = digest(p)
            if got != f['sha256']:
                return dict(path=f['path'], error='SHA256 mismatch', expected=f['sha256'], actual=got)
        return None
    errors = []
    with ThreadPoolExecutor(max_workers=4) as pool:
        for i, error in enumerate(pool.map(one, inventory['files']), 1):
            if error:
                errors.append(error)
            if i % 5000 == 0:
                print(f'Checked {i}/{len(inventory["files"])} files', flush=True)
    report = dict(checked_at=datetime.now(timezone.utc).isoformat(), files=len(inventory['files']),
                  sha256_files=sum('sha256' in f for f in inventory['files']),
                  best_checkpoints=len(inventory['completed']), errors=errors)
    save(audit / 'verification.json', report)
    print(json.dumps(report, ensure_ascii=False, indent=2), flush=True)
    if not errors:
        subprocess.run([sys.executable, str(ROOT / 'scripts/marlowe/index_completed_download.py'),
                        str(audit)], check=True)
    return 1 if errors else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('audit', type=Path)
    parser.add_argument('action', choices=['prepare', 'transfer', 'verify'])
    args = parser.parse_args()
    audit = args.audit.resolve()
    inventory = json.loads((audit / 'remote_inventory.json').read_text())
    return globals()[args.action](audit, inventory)


if __name__ == '__main__':
    sys.exit(main())
